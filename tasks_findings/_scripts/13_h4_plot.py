"""T13 -- H4 aware-target Stackelberg figure (single-panel rewrite).

Loads the H4 sweep cache
(`game_experiments/_cache_v2/H4.pkl`, generated by
`game_experiments/run_h4.py`) and the passive-target C4 baseline
(`game_experiments/_cache_v2/C4.pkl`), and emits the publication-quality
figure `paper/figures/fig_h4_aware_target.{pdf,svg}`.

This is a paste-in copy of the plot function now living in
`game_experiments/run_h4.py:plot`, for the finding record. All
descriptive content (ratio scale, k=4 corner interpretation, k=0
baseline value, target-follower budgets) lives in the LaTeX caption,
not on the axes.

Reproduce (fast; loads pickles only):

    /vol/miltank/users/kaiserj/Collusion_Gametheory/.venv/bin/python \
        tasks_findings/_scripts/13_h4_plot.py
"""
from __future__ import annotations

import pickle
import sys
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path("/vol/miltank/users/kaiserj/Collusion_Gametheory")
sys.path.insert(0, str(ROOT))

from game.style import (
    apply_paper_style, PRIMARY_BLUE, PRIMARY_ORANGE, column_size,
)

H4_CACHE = ROOT / "game_experiments" / "_cache_v2" / "H4.pkl"
C4_CACHE = ROOT / "game_experiments" / "_cache_v2" / "C4.pkl"
FIG_PDF = ROOT / "paper" / "figures" / "fig_h4_aware_target.pdf"
FIG_SVG = ROOT / "paper" / "figures" / "fig_h4_aware_target.svg"

# Coalition action grid (must match run_h4.py).
EPS_MIN, EPS_MAX = 0.5, 64.0
COAL_GRID = np.logspace(np.log10(EPS_MIN), np.log10(EPS_MAX), 14)


def main() -> None:
    apply_paper_style()

    data = pickle.load(open(H4_CACHE, "rb"))
    per_k = [r for r in data["per_k"] if r.get("feasible")]
    if not per_k:
        print("no feasible aware-target rows; aborting", file=sys.stderr)
        sys.exit(1)

    passive_d = pickle.load(open(C4_CACHE, "rb"))
    passive = {r["k"]: r for r in passive_d["rows"]}

    ks_aware = [r["k"] for r in per_k]
    A_aware = [r["A_target"] for r in per_k]

    # k=4 interior local optimum: exclude the two grid-floor coalition
    # actions and re-take the target-BR argmax over A_t. Plotted as a
    # hollow marker; the caption explains it.
    interior_pts = []
    for r in per_k:
        if r["k"] < 4:
            continue
        interior = [row for row in r["target_br_curve"]
                    if row["ec"] > COAL_GRID[1] * 1.01]
        best = max(interior, key=lambda row: row["A_target"])
        interior_pts.append((r["k"], best["A_target"]))

    # Passive curve on k=0..4 (reloaded from C4).
    ks_curve = [0] + ks_aware
    A_passive = [passive.get(k, {}).get("A_target", float("nan"))
                 for k in ks_curve]

    fig, ax = plt.subplots(figsize=column_size(rows=1, aspect=0.75))
    ax.plot(ks_curve, A_passive, "s--", color=PRIMARY_ORANGE,
            markersize=4.5, lw=1.1, markeredgewidth=0,
            label=r"passive target")
    ax.plot(ks_aware, A_aware, "o-", color=PRIMARY_BLUE,
            markersize=4.5, lw=1.3, markeredgewidth=0,
            label=r"aware target (Stackelberg)")
    if interior_pts:
        pk = [p[0] for p in interior_pts]
        pA = [p[1] for p in interior_pts]
        ax.plot(pk, pA, "o", color=PRIMARY_BLUE, markersize=5.5,
                markerfacecolor="white", markeredgewidth=1.1)

    ax.set_yscale("log")
    ax.set_xticks([0, 1, 2, 3, 4])
    ax.set_ylim(8e-3, 1.0)
    ax.set_xlim(-0.25, 4.25)
    ax.set_xlabel(r"coalition size $k$")
    ax.set_ylabel(r"target advantage $A_t^\star(k)$")
    ax.legend(frameon=False, loc="center right")

    plt.tight_layout()
    FIG_PDF.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG_PDF)
    fig.savefig(FIG_SVG)
    plt.close(fig)
    print(f"wrote {FIG_PDF}")
    print(f"wrote {FIG_SVG}")


if __name__ == "__main__":
    main()
